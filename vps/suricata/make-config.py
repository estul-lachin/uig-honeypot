#!/usr/bin/env python3
"""Write the honeypot's Suricata config: the package's suricata.yaml with a few settings replaced.

Suricata's own `include` merges lists by index, which would leave the package's other outputs in
place, so this rewrites the whole file instead. Run by setup.sh on the VPS; checked there with
`suricata -T`.

  make-config.py BASE OUT HOME_NET          HOME_NET like "[172.18.0.5/32,172.19.0.0/16]"

What changes, and why:
  - HOME_NET is this VPS and the Cowrie network, so "inbound" means from the internet.
  - Capture on eth0 with af-packet, before Docker's NAT, so alerts carry the real source address.
  - Outputs: eve.json holds alerts only (no flow, DNS, HTTP or other protocol logs), and stats.json
    holds engine counters every 5 minutes (drops, memory). Nothing else is written.
  - Small memcaps and the "low" detection profile: the VPS has 2 GB, and Cowrie must keep running.
    The systemd drop-in also caps Suricata's memory, so it is restarted instead of the OOM killer
    picking a process.
"""

import sys

import yaml


def main(base, out, home_net):
    with open(base, encoding="utf-8") as f:
        c = yaml.safe_load(f)

    c.setdefault("vars", {}).setdefault("address-groups", {})["HOME_NET"] = home_net
    c["af-packet"] = [
        {"interface": "eth0", "cluster-id": 99, "cluster-type": "cluster_flow", "defrag": True,
         "tpacket-v3": True},  # recommended when only watching (not inline)
        {"interface": "default"},
    ]
    c["outputs"] = [
        {"eve-log": {"enabled": True, "filetype": "regular", "filename": "eve.json",
                     "types": [{"alert": {"payload": False, "packet": False, "metadata": True,
                                          "tagged-packets": False}}]}},
        {"eve-log": {"enabled": True, "filetype": "regular", "filename": "stats.json",
                     "types": [{"stats": {"totals": True, "threads": False, "deltas": False}}]}},
    ]
    c["stats"] = {"enabled": True, "interval": 300}
    c["default-rule-path"] = "/var/lib/suricata/rules"
    c["rule-files"] = ["suricata.rules"]
    c["max-pending-packets"] = 1024

    detect = c.setdefault("detect", {})
    detect["profile"] = "low"
    detect["sgh-mpm-context"] = "single"
    c.setdefault("flow", {})["memcap"] = "32mb"
    stream = c.setdefault("stream", {})
    stream["memcap"] = "32mb"
    stream.setdefault("reassembly", {})["memcap"] = "64mb"
    c.setdefault("defrag", {})["memcap"] = "16mb"
    c.setdefault("host", {})["memcap"] = "16mb"

    with open(out, "w", encoding="utf-8") as f:
        f.write("%YAML 1.1\n---\n")
        f.write("# Generated by /opt/uig-honeypot/suricata/make-config.py from the package's suricata.yaml.\n")
        f.write("# Do not edit; change make-config.py in the uig-honeypot repo and run ./hp nsm-setup.\n")
        yaml.safe_dump(c, f, default_flow_style=False, sort_keys=False)


if __name__ == "__main__":
    if len(sys.argv) != 4:
        sys.exit(__doc__)
    main(*sys.argv[1:])
