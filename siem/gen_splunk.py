#!/usr/bin/env python3
"""Generate the Splunk side of vps/ttp_rules.json, so tagging never drifts:

  app/honeypot/default/macros.conf        `cowrie_ttp` adds a multivalue field ttp
  app/honeypot/lookups/ttp_rules.csv      id,name,tactic for `lookup ttp_rules id AS ttp`

Run by `./hp siem up|reload`; the outputs are committed too, so the app also
works without running this. Usage: gen_splunk.py [--check]
"""

import csv
import io
import json
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
RULES = os.path.join(HERE, "..", "vps", "ttp_rules.json")
APP = os.path.join(HERE, "app", "honeypot")
MACROS = os.path.join(APP, "default", "macros.conf")
LOOKUP = os.path.join(APP, "lookups", "ttp_rules.csv")


def spl_string(s):
    """An SPL double-quoted string literal."""
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"') + '"'


def render():
    with open(RULES, encoding="utf-8") as fh:
        rules = json.load(fh)["rules"]
    parts = []
    for r in rules:
        if "event" in r:
            cond = f'eventid=={spl_string(r["event"])}'
        else:
            cond = f'match(input, {spl_string(r["pattern"])})'
        parts.append(f'if({cond}, "{r["id"]}", null())')
    macros = (
        "# Generated by siem/gen_splunk.py from vps/ttp_rules.json. Do not edit by hand.\n"
        "# Adds ttp, a multivalue field of MITRE ATT&CK technique IDs, to each Cowrie event.\n"
        "[cowrie_ttp]\n"
        "definition = eval ttp=mvdedup(mvappend(" + ", ".join(parts) + "))\n"
        "iseval = 0\n"
    )
    buf = io.StringIO()
    w = csv.writer(buf, lineterminator="\n")
    w.writerow(["id", "name", "tactic"])
    seen = set()
    for r in rules:
        if r["id"] not in seen:
            seen.add(r["id"])
            w.writerow([r["id"], r["name"], r["tactic"]])
    return {MACROS: macros, LOOKUP: buf.getvalue()}


def main(argv):
    out = render()
    if "--check" in argv:
        stale = [p for p, text in out.items()
                 if not os.path.exists(p) or open(p, encoding="utf-8").read() != text]
        for p in stale:
            print("out of date:", os.path.relpath(p, HERE), file=sys.stderr)
        return 1 if stale else 0
    for p, text in out.items():
        os.makedirs(os.path.dirname(p), exist_ok=True)
        with open(p, "w", encoding="utf-8") as fh:
            fh.write(text)
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
